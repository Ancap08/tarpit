// `npm run sim:specials` (milestone 28): run the special search
// (src/sim/specialSearch.ts) for every plan and map and write the result to
// src/sim/specialLists.ts. Each plan and map is searched in its own child
// process, in parallel; the whole run takes a few minutes. Pass
// plan:level:map triples (for example `combo:normal:meadow`) to search only
// those and print them without writing the file.
import { spawn } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { runnerImport } from 'vite';
import type * as Search from '../src/sim/specialSearch';
import type * as Sim from '../src/sim/index';

const root = fileURLToPath(new URL('..', import.meta.url));
const load = async <T>(path: string): Promise<T> =>
  (await runnerImport<T>(path, { root, configFile: false, logLevel: 'error' })).module;

type Job = { plan: 'combo' | 'hard'; level: Sim.Difficulty; map: Sim.MapId };
const PLANS = ['combo', 'hard'] as const;
const jobName = (j: Job): string => `${j.plan}:${j.level}:${j.map}`;
const parseJob = (arg: string): Job => {
  const [plan, level, map] = arg.split(':') as [Job['plan'], Sim.Difficulty, Sim.MapId];
  return { plan, level, map };
};

if (process.argv[2] === '--job') {
  // Child: one search, JSON on stdout.
  const { plan, level, map } = parseJob(process.argv[3]);
  const sim = await load<typeof Sim>('/src/sim/index.ts');
  const search = await load<typeof Search>('/src/sim/specialSearch.ts');
  const planActions = plan === 'combo' ? sim.COMBO_PLANS[map] : sim.HARD_PLANS[map];
  process.stdout.write(JSON.stringify(search.searchSpecials(planActions, level, map)));
  process.exit(0);
}

const sim = await load<typeof Sim>('/src/sim/index.ts');
const asked = process.argv.slice(2);
const jobs: Job[] = asked.length
  ? asked.map(parseJob)
  : PLANS.flatMap((plan) => sim.DIFFICULTIES.flatMap((level) => sim.MAP_IDS.map((map) => ({ plan, level, map }))));

const started = Date.now();
const results = await Promise.all(
  jobs.map(
    (job) =>
      new Promise<{ job: Job; list: unknown[] }>((resolve, reject) => {
        const child = spawn(process.execPath, [...process.execArgv, fileURLToPath(import.meta.url), '--job', jobName(job)], {
          stdio: ['ignore', 'pipe', 'inherit'],
        });
        let out = '';
        child.stdout.on('data', (chunk: Buffer) => (out += chunk.toString()));
        child.on('exit', (code) => {
          if (code !== 0) return reject(new Error(`${jobName(job)} exited ${code}`));
          console.error(`${jobName(job)} done after ${((Date.now() - started) / 1000).toFixed(0)} s`);
          resolve({ job, list: JSON.parse(out) as unknown[] });
        });
      }),
  ),
);

const fmt = (list: unknown[]): string =>
  `[\n${list.map((c) => `        ${c === null ? 'null' : JSON.stringify(c).replace(/"(\w+)":/g, '$1: ').replace(/,(?=\w+: )/g, ', ').replace(/"/g, "'").replace(/^\{/, '{ ').replace(/\}$/, ' }')},`).join('\n')}\n      ]`;

if (asked.length) {
  for (const { job, list } of results) console.log(jobName(job), JSON.stringify(list));
} else {
  const list = (plan: Job['plan'], level: Sim.Difficulty, map: Sim.MapId) =>
    results.find((r) => r.job.plan === plan && r.job.level === level && r.job.map === map)!.list;
  const body = PLANS.map(
    (plan) =>
      `  ${plan}: {\n${sim.DIFFICULTIES.map(
        (level) => `    ${level}: {\n${sim.MAP_IDS.map((map) => `      ${map}: ${fmt(list(plan, level, map))},`).join('\n')}\n    },`,
      ).join('\n')}\n  },`,
  ).join('\n');
  const file = `// Generated by \`npm run sim:specials\` (scripts/special-search.ts) from the
// special search in specialSearch.ts (milestone 28). Do not edit by hand:
// change the game or the search, then regenerate. specialSearch.test.ts
// checks it against the search.
//
// Per plan and map, entry i is wave i + 1's special: a special fired at the
// centre of cell (col, row) when the wave tick counter reaches atWaveTick,
// or null for no special that wave. SPECIAL_LISTS[plan][level][map] is
// searched with that map's plan ('combo': COMBO_PLANS, 'hard': HARD_PLANS)
// played on that level.

import type { Difficulty } from './difficulty';
import type { MapId } from './map';
import type { SpecialType } from './specials';

export interface StoredSpecial {
  special: SpecialType;
  col: number;
  row: number;
  atWaveTick: number;
}

/** The plans a special list is searched for. */
export type SpecialPlanId = 'combo' | 'hard';

export const SPECIAL_LISTS: Readonly<Record<SpecialPlanId, Readonly<Record<Difficulty, Readonly<Record<MapId, readonly (StoredSpecial | null)[]>>>>>> = {
${body}
};
`;
  writeFileSync(new URL('../src/sim/specialLists.ts', import.meta.url), file);
  console.error(`wrote src/sim/specialLists.ts after ${((Date.now() - started) / 1000).toFixed(0)} s`);
}
